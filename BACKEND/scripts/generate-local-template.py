"""Generate a LOCAL-ONLY SAM template from the deployed application's template.

Replace the external LayerArn with a local layer built from authored source and
requirements.txt. Build with --use-container, then invoke the BUILT template at
.aws-sam/build/template.yaml. This does not emulate AWS services or deploy them.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "template.yaml"
TARGET = ROOT / "template.local.yaml"

LOCAL_LAYER_RESOURCE = """  PlataformaAtiLayerLocal:
    Type: AWS::Serverless::LayerVersion
    Properties:
      LayerName: plataforma-ati-layer-local
      ContentUri: 01_layers/plataforma_ati/
      CompatibleRuntimes:
        - python3.14
      CompatibleArchitectures:
        - x86_64
      RetentionPolicy: Delete
    Metadata:
      BuildMethod: makefile
      BuildArchitecture: x86_64

"""


def render_local_template(content: str) -> str:
    """Transform known references and fail loudly when the source drifts."""
    if "PlataformaAtiLayerLocal:" in content:
        raise ValueError("Input already contains the local layer; use template.yaml.")
    if not re.search(r"Layers:\n\s+- !Ref LayerArn(?:\n|$)", content):
        raise ValueError("Expected Globals.Function.Layers with !Ref LayerArn.")
    if "  LayerArn:\n    Type: String\n" not in content:
        raise ValueError("Expected the LayerArn string parameter.")
    if "IOT_POLICY: !Ref DeviceIoTPolicy" not in content:
        raise ValueError("Expected the DeviceIoTPolicy reference.")

    # Retain the parameter, but it no longer needs an external ARN locally.
    content = content.replace(
        "  LayerArn:\n    Type: String\n",
        '  LayerArn:\n    Type: String\n    Default: ""\n',
        1,
    )
    content = re.sub(r"!Ref LayerArn\b", "!Ref PlataformaAtiLayerLocal", content)
    # SAM local needs the physical policy name rather than the resource logical ID.
    content = content.replace(
        "IOT_POLICY: !Ref DeviceIoTPolicy",
        "IOT_POLICY: !Sub 'plataforma-ati-iot-device-policy-${Stage}'",
    )
    content, count = re.subn(
        r"^Resources:\n",
        "Resources:\n" + LOCAL_LAYER_RESOURCE,
        content,
        count=1,
        flags=re.MULTILINE,
    )
    if count != 1:
        raise ValueError("Expected one top-level Resources section.")
    return (
        "# GENERATED by scripts/generate-local-template.py. DO NOT DEPLOY.\n"
        "# Build with --use-container; invoke .aws-sam/build/template.yaml.\n"
        + content
    )


def main() -> None:
    try:
        result = render_local_template(SOURCE.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        raise SystemExit(f"Cannot generate local template: {exc}") from exc
    TARGET.write_text(result, encoding="utf-8")
    print(f"Generated: {TARGET}")


if __name__ == "__main__":
    main()
